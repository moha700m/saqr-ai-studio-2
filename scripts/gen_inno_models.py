"""Generate installer/models.iss (Pascal model table) from the engine's model registry,
so the installer always downloads exactly the files and SHA-256 values the app verifies."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
reg = json.loads((root / "engine/saqr_engine/models/registry.json").read_text(encoding="utf-8"))["models"]
# Windows build ships DirectML/CPU -> FP32 swapper is the recommended one; GFPGAN is optional.
wanted = [m for m in reg if m["required"] or m["id"] in ("inswapper_128", "gfpgan_1.4")]
lines = ["// AUTO-GENERATED by scripts/gen_inno_models.py — do not edit", "",
         f"const ModelCount = {len(wanted)};", "",
         "procedure FillModels;", "begin"]
for i, m in enumerate(wanted):
    lines += [f"  ModelIds[{i}] := '{m['id']}';",
              f"  ModelFiles[{i}] := '{m['file']}';",
              f"  ModelUrls[{i}] := '{m['url']}';",
              f"  ModelHashes[{i}] := '{m['sha256']}';",
              f"  ModelSizesMB[{i}] := {round(m['size'] / 1e6)};",
              f"  ModelOptional[{i}] := {'True' if m['id'] == 'gfpgan_1.4' else 'False'};"]
lines += ["end;", ""]
out = root / "installer/models.iss"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} with {len(wanted)} models ({sum(m['size'] for m in wanted) / 1e6:.0f} MB)")
